"""
Agentic AI loop that orchestrates nutrition guidance using
Google Gemini (gemini-2.0-flash) with IBM Granite-style prompting.

Implements:
  - Intent detection  (plan / query)
  - Tool-like sub-routines: build_plan_prompt, build_query_prompt,
    save_plan_to_md
  - Guardrail checks  (harmful / out-of-scope content filter)
  - HAM (Helpful, Accurate, Mindful) tone enforcement via system prompt
  - Medical disclaimer injection on all plans
"""

from __future__ import annotations

import os
import re
import time
import textwrap
import datetime
from pathlib import Path

import google.generativeai as genai
from google.api_core.exceptions import ResourceExhausted
from dotenv import load_dotenv

# Load .env from the same directory as this file
load_dotenv(dotenv_path=Path(__file__).parent / ".env")

# ── Constants ────────────────────────────────────────────────
GEMINI_MODEL = "gemini-3.8-flash"

MEDICAL_DISCLAIMER = """
---
**⚕️ Medical Disclaimer**

The nutrition plan above is generated by an AI model for
**general informational purposes only**. It is **not** a substitute for
professional medical or dietary advice. Always consult a qualified
healthcare provider or registered dietitian before making significant
changes to your diet, especially if you have a medical condition such as
diabetes, hypertension, heart disease, kidney disease, or any other
chronic illness.

The creators of this application accept **no liability** for any health
outcomes resulting from following this AI-generated plan.
"""

SYSTEM_PROMPT = textwrap.dedent("""
You are NutriBot — a Helpful, Accurate, and Mindful (HAM) AI nutrition
assistant powered by IBM Granite-style intelligence.

Your responsibilities:
1. Provide personalised, evidence-based nutrition guidance.
2. Always respect the user's dietary preferences (vegetarian / non-vegetarian).
3. Tailor advice based on stated medical conditions (e.g., diabetes,
   hypertension) using safe, established dietary guidelines.
4. Factor in the user's location / regional food availability when
   suggesting meal ideas.
5. Maintain a warm, respectful, and encouraging tone at all times.
6. NEVER diagnose, prescribe medication, or give advice that could cause
   physical harm.
7. NEVER make up clinical facts — if uncertain, say so and recommend
   consulting a healthcare professional.
8. Use Markdown formatting for plans: headings, bullet lists, tables where
   appropriate.
9. Keep responses concise but complete. Avoid jargon unless explained.
""").strip()

GUARDRAIL_KEYWORDS = [
    "suicide", "self-harm", "overdose", "poison", "kill yourself",
    "illegal drug", "narcotic", "bomb", "weapon",
]

# ── Guardrail ────────────────────────────────────────────────

def _guardrail_check(text: str) -> bool:
    """Return True if the text triggers a safety guardrail."""
    lower = text.lower()
    return any(kw in lower for kw in GUARDRAIL_KEYWORDS)


# ── Gemini Client Factory ────────────────────────────────────

def _build_gemini_model(api_key: str) -> genai.GenerativeModel:
    """Configure and return a Gemini GenerativeModel instance."""
    genai.configure(api_key=api_key)
    return genai.GenerativeModel(
        model_name=GEMINI_MODEL,
        system_instruction=SYSTEM_PROMPT,
        generation_config=genai.GenerationConfig(
            temperature=0.7,
            max_output_tokens=1500,
            top_p=0.95,
        ),
    )


# ── Prompt Builders (Tool-like Sub-Routines) ─────────────────

def _build_plan_prompt(user_data: dict) -> str:
    """Construct the user message requesting a personalised nutrition plan."""
    name        = user_data.get("name", "User") or "User"
    age         = user_data.get("age", "unknown")
    diet_pref   = user_data.get("diet_preference", "not specified")
    med_history = user_data.get("medical_history", "none")
    city        = user_data.get("city", "")
    country     = user_data.get("country", "")
    location    = f"{city}, {country}".strip(", ") or "not specified"
    goal        = user_data.get("goal", "general health")

    return textwrap.dedent(f"""
    Please create a comprehensive, personalised 7-day nutrition plan for
    the following individual:

    - **Name**: {name}
    - **Age**: {age} years
    - **Dietary Preference**: {diet_pref}
    - **Medical History / Conditions**: {med_history}
    - **Location**: {location}
    - **Health Goal**: {goal}

    Structure the plan as:
    1. **Daily Macro Targets** (calories, protein, carbs, fats)
    2. **7-Day Meal Planner** (breakfast, lunch, dinner, snacks per day)
    3. **Foods to Include** (top 10 recommended foods for this profile)
    4. **Foods to Avoid** (especially considering medical conditions)
    5. **Hydration & Lifestyle Tips**
    6. **Sample Grocery List**

    Use tables where helpful. Keep suggestions practical and culturally
    relevant to {location}.
    """).strip()


def _build_query_prompt(question: str, user_data: dict) -> str:
    """Construct a contextual Q&A prompt."""
    context_parts = []
    if user_data.get("name"):
        context_parts.append(f"Name: {user_data['name']}")
    if user_data.get("age"):
        context_parts.append(f"Age: {user_data['age']}")
    if user_data.get("diet_preference"):
        context_parts.append(f"Diet: {user_data['diet_preference']}")
    if user_data.get("medical_history"):
        context_parts.append(f"Medical: {user_data['medical_history']}")
    context = "; ".join(context_parts) or "No profile provided"

    return textwrap.dedent(f"""
    User profile context: {context}

    User question: {question}

    Please answer the question accurately and helpfully, taking the
    user's profile into account where relevant.
    """).strip()


# ── Save Plan to Markdown ────────────────────────────────────

def save_plan_to_md(plan_text: str, user_data: dict, output_dir: str | None = None) -> Path:
    """Save the generated nutrition plan to a Markdown file."""
    if output_dir is None:
        output_dir = Path(__file__).parent / "plans"
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    name_slug = re.sub(r"[^\w]", "_", user_data.get("name", "user").lower())
    timestamp  = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    filename   = output_dir / f"nutrition_plan_{name_slug}_{timestamp}.md"

    header = textwrap.dedent(f"""
    # 🥗 Personalised Nutrition Plan

    **Generated by**: NutriBot — Agentic AI Nutritionist
    **Model**: Google Gemini ({GEMINI_MODEL})
    **Date**: {datetime.datetime.now().strftime("%B %d, %Y at %H:%M")}

    ---

    ## User Profile

    | Field              | Details                                          |
    |--------------------|--------------------------------------------------|
    | Name               | {user_data.get("name", "-")}                     |
    | Age                | {user_data.get("age", "-")} years                |
    | Diet Preference    | {user_data.get("diet_preference", "-")}          |
    | Medical History    | {user_data.get("medical_history", "-")}          |
    | Location           | {user_data.get("city", "")}, {user_data.get("country", "")} |
    | Health Goal        | {user_data.get("goal", "-")}                     |

    ---

    """).lstrip()

    content = header + plan_text + "\n\n" + MEDICAL_DISCLAIMER
    filename.write_text(content, encoding="utf-8")
    return filename


# ── Main Agentic Function ────────────────────────────────────

def run_nutrition_agent(
    user_data: dict,
    question: str | None,
    api_key: str,
    intent: str = "plan",   # "plan" | "query"
) -> tuple[str, Path | None]:
    """
    Agentic entry-point.

    Parameters
    ----------
    user_data : dict   — collected user profile fields
    question  : str    — user's Q&A question (intent="query" only)
    api_key   : str    — Gemini API key
    intent    : str    — "plan" or "query"

    Returns
    -------
    (response_text, saved_file_path | None)
    """

    # ── Guardrail: scan all inputs before calling LLM ────────
    check_text = " ".join([str(v) for v in user_data.values()])
    if question:
        check_text += " " + question
    if _guardrail_check(check_text):
        return (
            "⚠️ I'm unable to process this request as it may involve "
            "content that could be harmful. Please rephrase your query "
            "or consult a qualified healthcare professional.",
            None,
        )

    # ── Build prompt ─────────────────────────────────────────
    if intent == "plan":
        prompt = _build_plan_prompt(user_data)
    else:
        prompt = _build_query_prompt(question or "", user_data)

    # ── Call Gemini (with retry on 429 rate-limit) ───────────
    model      = _build_gemini_model(api_key)
    max_retries = 4
    base_wait   = 15   # seconds — free tier resets every 60 s

    for attempt in range(max_retries):
        try:
            response = model.generate_content(prompt)
            raw_text = response.text
            break                          # success — exit retry loop
        except ResourceExhausted as exc:
            if attempt < max_retries - 1:
                # Parse suggested retry delay from the error message if present
                wait = base_wait * (attempt + 1)
                import re as _re
                m = _re.search(r"retry in (\d+(?:\.\d+)?)", str(exc), _re.IGNORECASE)
                if m:
                    wait = max(int(float(m.group(1))) + 2, wait)
                time.sleep(wait)
            else:
                raise RuntimeError(
                    f"⏳ Gemini free-tier rate limit hit after {max_retries} retries. "
                    "Please wait ~1 minute and try again, or upgrade your Gemini API plan at "
                    "https://ai.google.dev/gemini-api/docs/rate-limits"
                ) from exc

    # ── Post-process ─────────────────────────────────────────
    if intent == "plan":
        final_text = raw_text + "\n\n" + MEDICAL_DISCLAIMER
        saved_path = save_plan_to_md(raw_text, user_data)
        return final_text, saved_path
    else:
        return raw_text, None
